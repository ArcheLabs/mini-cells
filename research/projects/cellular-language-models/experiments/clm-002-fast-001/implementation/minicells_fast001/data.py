"""Hash-counter generation after parent fixation; no historical corpus access."""

import hashlib
import json
import unicodedata
from pathlib import Path

import numpy as np
import torch
from tokenizers import Tokenizer

from .common import ROOT, atomic, digest, read, sha


class Draw:
    def __init__(self, key):
        self.key = key
        self.counter = 0

    def integer(self, high):
        value = int(hashlib.sha256((self.key + "/" + str(self.counter)).encode()).hexdigest(), 16)
        self.counter += 1
        return value % high

    def choice(self, values):
        return values[self.integer(len(values))]


def record(c, task, role, index, attempt=0):
    rng = Draw(sha([c["data"]["generation_seeds"][role], task, role, index, attempt]))
    low, high = c["data"]["numeric_ranges"][role]
    names = c["data"]["names"][role]
    name, friend = rng.choice(names), rng.choice(names)
    things = ["beads", "stones", "books", "buttons", "shells", "flowers", "cards", "apples"]
    colors = ["red", "blue", "green", "yellow", "purple", "white"]
    facts = []
    sentences = []
    for _ in range(8):
        a, b = low + rng.integer(high - low), low + rng.integer(high - low)
        thing, color = rng.choice(things), rng.choice(colors)
        if task == "Story":
            place = rng.choice(["garden", "village", "river", "library", "park", "farm"])
            action = rng.choice(["found", "carried", "counted", "collected", "shared"])
            sentences.append(
                f"{name} {action} {a} {color} {thing} near the {place}. {friend} smiled and helped {name} put the {thing} in a small wooden box."
            )
        else:
            operator = rng.choice(["+", "-"])
            if operator == "-":
                a, b = max(a, b), min(a, b)
            answer = a + b if operator == "+" else a - b
            facts.append([operator, a, b, answer])
            sentences.append(
                f"{name} writes a number problem in a book. The problem is {a} {operator} {b} = {answer}. {friend} reads the answer {answer} and checks the numbers carefully."
            )
    return " ".join(sentences), facts, rng


def generate(c, folder, *, counts=None):
    """Confirm is generated by the frozen rule, never selected using model outcomes."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    manifest_path = folder / "DATASET_MANIFEST.json"
    if manifest_path.exists():
        manifest = read(manifest_path)
        validate(c, folder, manifest)
        return manifest
    tokenizer_path = ROOT / c["tokenizer"]["path"]
    if digest(tokenizer_path) != c["tokenizer"]["sha256"]:
        raise RuntimeError("FAST_ORIGINAL_TOKENIZER_CHANGED")
    tokenizer = Tokenizer.from_file(str(tokenizer_path))
    expected_counts = counts or {
        "train": c["data"]["train_windows"],
        "confirm": c["data"]["confirm_windows"],
    }
    seen_text, seen_normalized, seen_windows, sample_ids = set(), set(), set(), set()
    seen_inputs, seen_targets = set(), set()
    files, roles = {}, {}
    for task in ("Story", "Arithmetic"):
        for role in ("train", "confirm"):
            rows, windows = [], []
            for index in range(expected_counts[role]):
                for attempt in range(c["data"]["duplicate_attempt_cap"]):
                    text, facts, rng = record(c, task, role, index, attempt)
                    text_sha = hashlib.sha256(text.encode()).hexdigest()
                    norm_sha = hashlib.sha256(
                        " ".join(unicodedata.normalize("NFKC", text).casefold().split()).encode()
                    ).hexdigest()
                    tokens = tokenizer.encode(text).ids + [tokenizer.token_to_id("<eos>")]
                    length = c["sequence_length"]
                    if len(tokens) < length + 1:
                        raise RuntimeError("FAST_GENERATOR_SHORT_RECORD")
                    offset = rng.integer(len(tokens) - length)
                    window = tokens[offset : offset + length + 1]
                    window_sha = sha(window)
                    input_sha, target_sha = sha(window[:-1]), sha(window[1:])
                    if (
                        text_sha not in seen_text
                        and norm_sha not in seen_normalized
                        and window_sha not in seen_windows
                        and input_sha not in seen_inputs
                        and target_sha not in seen_targets
                    ):
                        break
                else:
                    raise RuntimeError("FAST_DETERMINISTIC_DEDUP_EXHAUSTED_NO_REGISTRATION")
                sample_id = sha([c["experiment_id"], task, role, index])
                if sample_id in sample_ids:
                    raise RuntimeError("FAST_SAMPLE_ID_COLLISION")
                sample_ids.add(sample_id)
                seen_text.add(text_sha)
                seen_normalized.add(norm_sha)
                seen_windows.add(window_sha)
                seen_inputs.add(input_sha)
                seen_targets.add(target_sha)
                rows.append(
                    {
                        "sample_id": sample_id,
                        "raw_text_sha256": text_sha,
                        "normalized_text_sha256": norm_sha,
                        "window_sha256": window_sha,
                        "window_offset": offset,
                        "attempt": attempt,
                        "facts_sha256": sha(facts),
                    }
                )
                windows.append(window)
            name = task + "-" + role
            np.save(folder / (name + ".npy"), np.asarray(windows, dtype=np.int32))
            (folder / (name + ".json")).write_text(
                json.dumps(rows, sort_keys=True, separators=(",", ":")) + "\n"
            )
            for suffix in (".npy", ".json"):
                path = folder / (name + suffix)
                files[path.name] = {"bytes": path.stat().st_size, "sha256": digest(path)}
            roles[name] = {
                "records": len(rows),
                "effective_targets": len(rows) * c["sequence_length"],
                "no_cross_record_context": True,
            }
    manifest = {
        "schema": "minicells.fast001.dataset.v1",
        "experiment_id": c["experiment_id"],
        "config_sha256": sha(c),
        "generator_sha256": digest(Path(__file__)),
        "parent_fixed_before_generation": c["parent"],
        "tokenizer_sha256": c["tokenizer"]["sha256"],
        "roles": roles,
        "files": files,
        "train_confirm_exact_text_and_window_overlap": 0,
        "normalized_record_overlap": 0,
        "role_numeric_ranges": c["data"]["numeric_ranges"],
        "role_names": c["data"]["names"],
        "sample_id_count": len(sample_ids),
        "model_quality_used": False,
        "historical_data_loaded": False,
        "historical_fourteen_boundaries": "UNRESOLVED_NOT_A_PRECONDITION_FOR_THIS_NEW_SYNTHETIC_STUDY",
        "conclusion_scope": "CONTROLLED_GENERATOR_DISTRIBUTION_ONLY",
        "engineering_small_fixture": counts is not None,
    }
    atomic(manifest_path, manifest)
    return manifest


def validate(c, folder, manifest):
    if manifest["config_sha256"] != sha(c) or manifest["generator_sha256"] != digest(
        Path(__file__)
    ):
        raise RuntimeError("FAST_DATA_IDENTITY_CHANGED")
    for name, row in manifest["files"].items():
        path = Path(folder) / name
        if (
            path.is_symlink()
            or path.stat().st_size != row["bytes"]
            or digest(path) != row["sha256"]
        ):
            raise RuntimeError("FAST_DATA_FILE_CHANGED")


class Stream:
    def __init__(self, c, folder, seed, condition, phase, device="cpu"):
        self.c, self.seed, self.condition, self.phase, self.device = (
            c,
            seed,
            condition,
            phase,
            device,
        )
        self.manifest = read(Path(folder) / "DATASET_MANIFEST.json")
        self.pool_sha = sha(self.manifest)
        self.arrays = {
            task: np.load(Path(folder) / (task + "-train.npy"), mmap_mode="r")
            for task in ("Story", "Arithmetic")
        }
        self.rng = np.random.default_rng(seed + c["phase_seed_offsets"][phase])
        self.step = 0

    def next(self):
        n = self.c["batch_size"]
        tasks = (
            ["Story"] * n
            if self.condition == "S"
            else ["Story"] * (n // 2) + ["Arithmetic"] * (n // 2)
        )
        rows = []
        for task in tasks:
            row = np.array(
                self.arrays[task][int(self.rng.integers(len(self.arrays[task])))], copy=True
            )
            values = torch.tensor(row, dtype=torch.long, device=self.device).unsqueeze(0)
            rows.append(
                {
                    "task": task,
                    "x": values[:, :-1],
                    "y": values[:, 1:],
                    "valid": torch.ones_like(values[:, 1:]),
                }
            )
        order = self.rng.permutation(n)
        self.step += 1
        return [rows[int(i)] for i in order]

    def state(self):
        return {
            "pool_sha": self.pool_sha,
            "seed": self.seed,
            "condition": self.condition,
            "phase": self.phase,
            "step": self.step,
            "rng": self.rng.bit_generator.state,
        }

    def restore(self, state):
        if any(state[k] != self.state()[k] for k in ("pool_sha", "seed", "condition", "phase")):
            raise RuntimeError("FAST_STREAM_IDENTITY_CHANGED")
        self.rng.bit_generator.state = state["rng"]
        self.step = state["step"]


def evaluation_rows(c, folder, device, role="confirm", condition=None):
    for task in ("Story", "Arithmetic"):
        if condition == "S" and task == "Arithmetic":
            continue
        array = np.load(Path(folder) / (task + "-" + role + ".npy"), mmap_mode="r")
        limit = len(array) if role == "confirm" else (8 if condition == "S" else 4)
        batch_size = c["evaluation_batch_size"] if role == "confirm" else 1
        for offset in range(0, limit, batch_size):
            value = torch.tensor(
                np.array(array[offset : min(limit, offset + batch_size)], copy=True),
                dtype=torch.long,
                device=device,
            )
            yield {
                "task": task,
                "x": value[:, :-1],
                "y": value[:, 1:],
                "valid": torch.ones_like(value[:, 1:]),
            }
